let currentLang = (typeof localStorage !== "undefined" && localStorage.getItem("halka_lang")) || "en";

function t(key){
  const entry = STRINGS[key];
  if (!entry) return key;
  return entry[currentLang] || entry.en || key;
}

function categoryLabel(catKey){
  const entry = CATEGORY_STRINGS[catKey];
  if (!entry) return catKey;
  return entry.label[currentLang] || entry.label.en || catKey;
}

function setLanguage(code){
  currentLang = code;
  try { localStorage.setItem("halka_lang", code); } catch (e) { /* storage unavailable — language just won't persist */ }
  applyLanguage();
}

/* Updates every static (non-JS-generated) piece of chrome, then re-renders
 * whatever's currently on screen so JS-generated content picks up the new
 * language too. Falls back silently to English text already baked into the
 * HTML if a translation is ever missing, rather than leaving a blank. */
function applyLanguage(){
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    el.innerHTML = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  const sel = document.getElementById("langSelect");
  if (sel) sel.value = currentLang;

  // Re-render whatever view is currently active so generated strings (table
  // headers, tab labels, quick chips) switch language immediately too.
  if (typeof currentKey !== "undefined" && currentKey){
    if (document.getElementById("resultArea")) renderList();
    if (document.getElementById("matrixOverlay") && document.getElementById("matrixOverlay").classList.contains("show")) renderMatrix();
    if (document.getElementById("promiseOverlay") && document.getElementById("promiseOverlay").classList.contains("show")) renderPromiseCanvas();
  } else if (document.getElementById("topBanner") && !document.querySelector("#topBanner[data-i18n]")) {
    // No constituency picked yet, but the banner was set dynamically to the
    // default text (not via data-i18n) — refresh it to match the new language.
    document.getElementById("topBanner").textContent = t("bannerDefault");
  }
}

function buildLangSwitcher(){
  let html = '<select id="langSelect" class="lang-select" onchange="setLanguage(this.value)" aria-label="' + t("langButtonLabel") + '">';
  LANGUAGES.forEach(l => {
    html += '<option value="' + l.code + '"' + (l.code === currentLang ? " selected" : "") + '>' + l.label + '</option>';
  });
  html += '</select>';
  return html;
}
